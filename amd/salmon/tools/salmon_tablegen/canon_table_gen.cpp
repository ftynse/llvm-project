// This file implements a TableGen backend that walks every `SalmonOp`
// record in `amd/salmon/td/SalmonAMDGCN.td` and emits the static
// `kCanonTable[]` array consumed by `OpcodeMap::build`. Each row is the
// pair `{AMDGPU::<inst-record-name>, SemOp::<sem-string>}`.
//
// `SalmonOp` is a Salmon-side decorator class on top of LLVM's
// `Instruction`. By moving the table into TableGen we get:
//
//   * Type-checked family expansion via `multiclass` + `!cast<Instruction>`
//     on the Salmon side (`SalmonMUBUF4`, `SalmonSMEM3`, ...).
//   * A single source of truth that other `salmon-tblgen` backends can
//     iterate without rebuilding their own list of supported opcodes.
//   * A natural place for additional per-instruction Salmon metadata
//     (handler hints, gfx-rev gating, conformance tags) to grow as
//     extra fields on `SalmonOp`.
//
// The semantics of the emitted table match the previous hand-rolled
// `kCanonTable[]` exactly: when the same `Instruction` is bound to two
// `SemOp` strings, the *first* binding in source order wins (matches the
// runtime's `DenseMap::try_emplace`). Suppressed duplicates are emitted
// as `// duplicate-of` comments next to the winning row so the
// generated header still surfaces the intended-but-superseded mapping.
//
//===----------------------------------------------------------------------===//

